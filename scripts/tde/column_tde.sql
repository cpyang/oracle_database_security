  DBMS_OUTPUT.PUT_LINE('');
  DBMS_OUTPUT.PUT_LINE('ENCRYPT options:');
  DBMS_OUTPUT.PUT_LINE('  - ENCRYPT: Encrypts with salt (higher security)');
  DBMS_OUTPUT.PUT_LINE('  - ENCRYPT NO SALT: Encrypts without salt (supports indexing/search)');
  DBMS_OUTPUT.PUT_LINE('========================================');
END;
